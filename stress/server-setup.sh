#!/bin/sh
# Set up (or refresh) the stress-test copy of InH-Ticketing on a PRIVATE test
# server. STRESS-TEST BRANCH ONLY. Fake data only, never real data.
#
#   sh stress/server-setup.sh [hostname]        hostname default: inh-stress.test
#   sh stress/server-setup.sh --down            stop it and delete its data
#
# What it does:
#   1. checks Docker (Engine with Compose 2.24.4 or later) and openssl;
#   2. writes a stress-test .env (random secrets, NO Microsoft 365 credentials,
#      no email) unless one exists, and refuses to touch a non-stress .env;
#   3. makes a self-signed certificate for the hostname;
#   4. builds and starts the app (capped at 2 CPUs / 4 GB, see compose.stress.yaml);
#   5. generates fake data: 300 requesters, 5 agents, 12,000 tickets over 5 years.
#      Override with STRESS_DATA_ARGS, e.g. STRESS_DATA_ARGS="--tickets 50000".

set -eu
cd "$(dirname "$0")/.."

log() { printf '%s %s\n' "$(date '+%H:%M:%S')" "$*"; }
die() { log "SETUP FAILED: $*" >&2; exit 1; }
dc() { docker compose -f compose.yaml -f compose.prod.yaml -f compose.stress.yaml "$@"; }

if [ "${1:-}" = "--down" ]; then
	log "Stopping the stress-test copy and deleting its data (database, attachments)"
	dc --profile loadgen down -v
	exit 0
fi
HOST=${1:-inh-stress.test}

# 1. Prerequisites
command -v docker > /dev/null 2>&1 || die "Docker isn't installed (see stress/README.md)"
command -v openssl > /dev/null 2>&1 || die "openssl isn't installed: apt install openssl"
version=$(docker compose version --short 2> /dev/null) || die "the Docker Compose plugin isn't installed"
version=${version#v}
major=${version%%.*}; rest=${version#*.}; minor=${rest%%.*}
case $rest in *.*) patch=${rest#*.}; patch=${patch%%[!0-9]*} ;; *) patch=0 ;; esac
# 2.24.4 or later: compose.stress.yaml uses "!override".
[ "$major" -gt 2 ] || { [ "$major" -eq 2 ] && { [ "$minor" -gt 24 ] || { [ "$minor" -eq 24 ] && [ "${patch:-0}" -ge 4 ]; }; }; } ||
	die "Docker Compose $version is too old; 2.24.4 or later is needed"

# 2. The .env: a stress-test one only.
if [ -f .env ]; then
	grep -q '^STRESS_TEST_MODE=1' .env ||
		die ".env exists and isn't a stress-test one. This must not run where the real app is configured."
	log "Keeping the existing stress-test .env"
else
	log "Writing a stress-test .env for $HOST"
	umask 077
	cat > .env <<EOF
# Stress-test server ONLY. Generated by stress/server-setup.sh. Fake data.
STRESS_TEST_MODE=1
DJANGO_DEBUG=False
DJANGO_SECRET_KEY=$(openssl rand -hex 32)
DJANGO_ALLOWED_HOSTS=$HOST,localhost
DJANGO_CSRF_TRUSTED_ORIGINS=https://$HOST
DJANGO_SECURE_HSTS_SECONDS=0
HELPDESK_HOSTNAME=$HOST
SITE_URL=https://$HOST
TIME_ZONE=America/Los_Angeles
POSTGRES_PASSWORD=$(openssl rand -hex 24)
# No Microsoft 365 and no email, on purpose (the app refuses to start otherwise).
ENTRA_TENANT_ID=
ENTRA_CLIENT_ID=
ENTRA_CLIENT_SECRET=
EMAIL_BACKEND=file
INBOUND_EMAIL=off
EOF
	umask 022
fi

# The site signs everyone in automatically, so publish it on the Tailscale
# address only (or, without Tailscale, on this machine only).
BIND=$(tailscale ip -4 2> /dev/null | head -n 1) || BIND=
if [ -n "$BIND" ]; then
	log "Publishing the site on the Tailscale address $BIND only"
else
	BIND=127.0.0.1
	log "Tailscale not found: publishing the site on this machine only (127.0.0.1)"
fi
sed -i '/^STRESS_BIND_ADDRESS=/d' .env
echo "STRESS_BIND_ADDRESS=$BIND" >> .env

# 3. Self-signed certificate
mkdir -p stress/.certs stress/reports
if [ ! -f stress/.certs/fullchain.pem ]; then
	log "Making a self-signed certificate for $HOST"
	openssl req -x509 -newkey rsa:2048 -nodes -days 365 -subj "/CN=$HOST" \
		-addext "subjectAltName=DNS:$HOST" \
		-keyout stress/.certs/privkey.pem -out stress/.certs/fullchain.pem 2> /dev/null ||
		die "couldn't make the certificate"
fi

# 4. Build and start
log "Building and starting the app (this takes a few minutes the first time)"
dc up -d --build || die "docker compose up failed"
log "Waiting for the app to be ready"
i=0
until dc exec -T web python -c "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/healthz', timeout=3)" 2> /dev/null; do
	i=$((i + 1))
	[ "$i" -lt 60 ] || die "the app didn't become ready within 2 minutes: docker compose logs web"
	sleep 2
done

# 5. Fake data
if dc exec -T web python manage.py stress_counts | grep -q '"tickets": 0,'; then
	log "Generating fake data"
	# shellcheck disable=SC2086
	dc exec -T web python manage.py generate_load_data ${STRESS_DATA_ARGS:-} || die "generating data failed"
else
	log "Fake data already present (to replace it: docker compose ... exec web python manage.py generate_load_data --clear)"
fi
log "Data: $(dc exec -T web python manage.py stress_counts)"

echo
echo "Ready. The stress-test copy is running at https://$HOST (self-signed certificate)."
echo "To browse it from your PC, point $HOST at $BIND in your PC's hosts file."
echo "No sign-in: you're a fake IT agent. Add ?as=stress-req-0001 to the address to be a requester."
echo
echo "Run the tests:   sh stress/run.sh expected     (or: peak, stress, soak, all)"
echo "Reports go to:   stress/reports/"
